package com.otectus.immersivetanning.compat.geneticanimals;

/** How a Genetic Animals death turns into raw hides ({@code compat.geneticAnimals.hideMode}). */
public enum HideMode {
    /** The skin Genetic Animals actually drops becomes raw hides; no skin, no hide. */
    NATIVE,
    /** Every eligible adult drops its species' hide, whatever Genetic Animals drops. */
    TANNING
}
